'use strict';
const { contextBridge, ipcRenderer, webFrame, webUtils } = require('electron');
// Text size is applied by the renderer (root font-size, src/i18n); zoom stays 1.
webFrame.setZoomFactor(1);
contextBridge.exposeInMainWorld('qr', {
  getSettings: () => ipcRenderer.invoke('qr:getSettings'),
  getVersion: () => ipcRenderer.invoke('qr:getVersion'),
  tutorialVideo: (lang) => ipcRenderer.invoke('qr:tutorialVideo', lang),
  setSettings: (s) => ipcRenderer.invoke('qr:setSettings', s),
  setFloatPos: (key, pos) => ipcRenderer.invoke('qr:setFloatPos', key, pos),
  catalogPatterns: (entries) => ipcRenderer.invoke('qr:catalogPatterns', entries),
  questionSample: (lang) => ipcRenderer.invoke('qr:questionSample', lang),
  newCustomer: (from, ids) => ipcRenderer.invoke('qr:newCustomer', from, ids),
  pickFiles: () => ipcRenderer.invoke('qr:pickFiles'),
  pickFolder: (opts) => ipcRenderer.invoke('qr:pickFolder', opts),
  pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch { return f.path || ''; } },
  process: (paths, job) => ipcRenderer.invoke('qr:process', paths, job),
  releaseImportCache: (job) => ipcRenderer.invoke('qr:importCache:release', job),
  listProjects: () => ipcRenderer.invoke('qr:projects:list'), saveProject: (id, data) => ipcRenderer.invoke('qr:projects:save', id, data),
  saveProjectsIndex: (idx) => ipcRenderer.invoke('qr:projects:index', idx), peekRfq: (paths) => ipcRenderer.invoke('qr:peekRfq', paths), peekMail: (paths) => ipcRenderer.invoke('qr:peekMail', paths),
  onNotify: (cb) => { const h = (_e, n) => cb(n); ipcRenderer.on('qr:notify', h); return () => ipcRenderer.removeListener('qr:notify', h); },
  onEvent: (cb) => { const h = (_e, ev) => cb(ev); ipcRenderer.on('qr:event', h); return () => ipcRenderer.removeListener('qr:event', h); },
  preview: (file, page, maxPx) => ipcRenderer.invoke('qr:preview', file, page, maxPx),
  questionsPreview: (parts, lang) => ipcRenderer.invoke('qr:questionsPreview', parts, lang),
  exportQuestions: (parts, lang, target) => ipcRenderer.invoke('qr:exportQuestions', parts, lang, target),
  exportSummary: (parts, kind, target) => ipcRenderer.invoke('qr:exportSummary', parts, kind, target),
  exportReport: (parts, lang, meta, target) => ipcRenderer.invoke('qr:exportReport', parts, lang, meta, target),
  listHistory: () => ipcRenderer.invoke('qr:history:list'),
  touchHistory: (entry) => ipcRenderer.invoke('qr:history:touch', entry),
  removeHistory: (id, deleteData) => ipcRenderer.invoke('qr:history:remove', id, deleteData),
  clearHistory: () => ipcRenderer.invoke('qr:history:clear'),
  loadProject: (id) => ipcRenderer.invoke('qr:projects:load', id),
  saveProjectAs: (id, state, label, target) => ipcRenderer.invoke('qr:projects:saveAs', id, state, label, target),
  pickProjectFile: (target) => ipcRenderer.invoke('qr:projects:pickOpen', target), importProject: (file) => ipcRenderer.invoke('qr:projects:import', file),
  exportRequirements: (parts, target) => ipcRenderer.invoke('qr:exportRequirements', parts, target),
  outlookSelection: () => ipcRenderer.invoke('qr:outlookSelection'),
  onImport: (cb) => { const h = (_e, files) => cb(files); ipcRenderer.on('qr:import', h); return () => ipcRenderer.removeListener('qr:import', h); },
  openPath: (p) => ipcRenderer.invoke('qr:openPath', p),
  stdConfirm: (s, c) => ipcRenderer.invoke('qr:std:confirm', s, c),
  stdUpload: (s, c, o) => ipcRenderer.invoke('qr:std:upload', s, c, o),
  stdOpen: (f) => ipcRenderer.invoke('qr:std:open', f),
  printers: () => ipcRenderer.invoke('qr:printers'),
  printDrawings: (payload) => ipcRenderer.invoke('qr:printDrawings', payload),
  print: (payload) => ipcRenderer.invoke('qr:print', payload),
  savePdf: (payload, target) => ipcRenderer.invoke('qr:savePdf', payload, target),
  savePdfEach: (payload, targetDir) => ipcRenderer.invoke('qr:savePdfEach', payload, targetDir),
  releaseUpdate: (action, payload) => ipcRenderer.invoke('qr:release-update', action, payload),
  onReleaseUpdate: (cb) => { const h = (_e, ev) => cb(ev); ipcRenderer.on('qr:release-update', h); return () => ipcRenderer.removeListener('qr:release-update', h); },
});
